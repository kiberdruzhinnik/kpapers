import { expect, test } from "@playwright/test"

async function signIn(page: import("@playwright/test").Page) {
  await page.goto("/")
  await page.getByLabel("Username").fill(process.env.OPERATOR_USERNAME ?? "operator")
  await page.getByLabel("Password").fill(process.env.OPERATOR_PASSWORD ?? "")
  await page.getByRole("button", { name: "Sign in" }).click()
  await expect(page.getByRole("heading", { name: "Overview" })).toBeVisible()
}

test("operator manages a feed, source folder, publication decision, and account session", async ({ page }) => {
  const feedName = `Browser test ${Date.now()}`
  await signIn(page)

  await page.getByRole("button", { name: /Feeds/ }).click()
  await page.getByRole("button", { name: "Create feed" }).click()
  await expect(page).toHaveURL(/\/manage\/feeds\/new$/)
  await page.reload()
  await page.getByLabel("Author name").fill(feedName)
  await page.getByLabel("Description (optional)").fill("Playwright workflow fixture")
  await page.getByLabel("Refresh interval (optional)").fill("2")
  const createdFeedResponse = page.waitForResponse((response) => response.url().endsWith("/api/management/feeds") && response.request().method() === "POST")
  await page.getByRole("button", { name: "Create feed" }).click()
  const createdFeed = await (await createdFeedResponse).json() as { id: string }
  await expect(page.getByRole("heading", { name: feedName })).toBeVisible()
  await expect(page.getByText(/\/feeds\//)).toBeVisible()
  await page.goto(`/manage/feeds/${createdFeed.id}`)
  await page.reload()
  await expect(page.getByRole("heading", { name: feedName })).toBeVisible()
  const rss = await page.request.get(`/feeds/${createdFeed.id}`, { maxRedirects: 0 })
  expect(rss.status()).toBe(200)
  expect(rss.headers()["content-type"]).toContain("xml")
  expect(await rss.text()).toContain("<rss")

  await page.getByRole("button", { name: "Edit details" }).click()
  const details = page.getByRole("region", { name: "Feed details" })
  await details.getByLabel("Author name").fill(`${feedName} Edited`)
  await details.getByRole("button", { name: "Save changes" }).click()
  await expect(details.getByRole("heading", { name: `${feedName} Edited` })).toBeVisible()
  await page.getByRole("button", { name: "Refresh feed" }).click()
  await expect(page.getByText("Feed refresh queued")).toBeVisible()

  await page.getByLabel("Add a year").fill("2026")
  await page.getByRole("button", { name: "Add year" }).click()
  await expect(page.locator("[data-slot='card-title']", { hasText: "2026" })).toBeVisible()
  await expect(page.getByRole("button", { name: "Expand 2026" })).toHaveAttribute("aria-expanded", "false")
  await page.getByRole("button", { name: "Expand 2026" }).click()
  await page.getByLabel("Month", { exact: true }).selectOption("11")
  await page.getByLabel("Public folder link").fill("fixture://current-month/")
  const createdMonthResponse = page.waitForResponse((response) => response.url().includes(`/api/management/feeds/${createdFeed.id}/years/2026/months/11`) && response.request().method() === "PUT")
  await page.getByRole("button", { name: "Link month" }).click()
  const createdMonth = await (await createdMonthResponse).json() as { id: string }
  await expect(page.getByRole("heading", { name: "November" })).toBeVisible()
  await page.reload()
  await expect(page.getByRole("button", { name: "Collapse 2026" })).toHaveAttribute("aria-expanded", "true")
  await expect(page.getByRole("heading", { name: "November" })).toBeVisible()
  const yearCard = page.locator("[data-slot='card-title']").filter({ hasText: "2026" }).locator("xpath=ancestor::*[@data-slot='card'][1]")
  const monthCard = page.getByRole("heading", { name: "November" }).locator("xpath=ancestor::*[@data-slot='card'][1]")

  await yearCard.getByRole("button", { name: "Refresh year" }).click()
  await expect(page.getByText("2026 refresh queued")).toBeVisible()
  await page.getByRole("button", { name: "Refresh now" }).click()
  await expect(page.getByText("November refresh queued")).toBeVisible()
  await page.getByRole("button", { name: "Fetch and parse" }).click()
  await expect(page.getByText("Folder scan complete")).toBeVisible({ timeout: 30_000 })

  await page.getByRole("button", { name: "Review PDFs" }).click()
  await expect(page).toHaveURL(new RegExp(`/manage/pdf-review/${createdFeed.id}/2026/${createdMonth.id}$`))
  await page.reload()
  await expect(page.getByRole("combobox", { name: "Feed" })).toHaveValue(createdFeed.id)
  await expect(page.getByRole("combobox", { name: "Year" })).toHaveValue("2026")
  await expect(page.getByRole("combobox", { name: "Month" })).toHaveValue(createdMonth.id)
  const alphaRow = page.locator("article").filter({ hasText: "article-alpha.pdf" })
  await expect(alphaRow).toContainText("Extraction success", { timeout: 30_000 })
  const decision = alphaRow.getByRole("combobox", { name: "Publication decision for article-alpha.pdf" })
  await decision.selectOption("exclude")
  await expect(page.getByText("Publication decision saved").first()).toBeVisible()
  const sourceLink = alphaRow.getByRole("link", { name: "View source PDF" })
  const sourceHref = await sourceLink.getAttribute("href")
  expect(sourceHref).toMatch(/^\/api\/management\/documents\/[^/]+\/source$/)
  const sourceResponse = await page.request.get(new URL(sourceHref ?? "", page.url()).toString(), { maxRedirects: 0 })
  expect(sourceResponse.status()).toBe(307)
  expect(decodeURIComponent(sourceResponse.headers().location ?? "")).toContain("/current-month/article-alpha.pdf")
  await page.getByRole("button", { name: "Back to feeds" }).click()
  await expect(page).toHaveURL(new RegExp(`/manage/feeds/${createdFeed.id}$`))
  await monthCard.getByRole("button", { name: "Review PDFs" }).click()
  await expect(page.getByRole("combobox", { name: "Publication decision for article-alpha.pdf" })).toHaveValue("exclude")
  const reloadedAlpha = page.locator("article").filter({ hasText: "article-alpha.pdf" })
  await reloadedAlpha.getByRole("combobox", { name: "Publication decision for article-alpha.pdf" }).selectOption("include")
  await expect(page.getByText("Publication decision saved").first()).toBeVisible()
  await page.getByRole("combobox", { name: "Publication decision for article-alpha.pdf" }).selectOption("automatic")
  await expect(page.getByText("Publication decision saved").first()).toBeVisible()
  await page.getByRole("button", { name: "Back to feeds" }).click()

  await monthCard.getByRole("button", { name: "Archive", exact: true }).click()
  await expect(page.getByRole("alertdialog")).toContainText("Archive November?")
  await page.getByRole("alertdialog").getByRole("button", { name: "Archive month" }).click()
  await expect(monthCard.getByRole("button", { name: "Restore month" })).toBeVisible()
  await monthCard.getByRole("button", { name: "Restore month" }).click()
  await expect(page.getByRole("button", { name: "Refresh now" })).toBeVisible()

  await yearCard.getByRole("button", { name: "Archive", exact: true }).first().click()
  await page.getByRole("alertdialog").getByRole("button", { name: "Archive year" }).click()
  await expect(yearCard.getByRole("button", { name: "Restore year" })).toBeVisible()
  await yearCard.getByRole("button", { name: "Restore year" }).click()
  await expect(page.getByRole("button", { name: "Refresh year" })).toBeVisible()

  await monthCard.getByRole("button", { name: "Delete permanently" }).click()
  await expect(page.getByRole("alertdialog")).toContainText("Permanently delete November 2026?")
  await page.getByRole("alertdialog").getByRole("button", { name: "Delete permanently" }).click()
  await expect(page.getByText(/No months linked yet/)).toBeVisible()

  await page.getByRole("button", { name: `More actions for ${feedName} Edited` }).click()
  await page.getByRole("alertdialog").getByRole("button", { name: "Archive feed" }).click()
  await expect(page.getByRole("alertdialog")).toBeHidden()
  await page.getByRole("button", { name: `${feedName} Edited`, exact: true }).click()
  await page.getByRole("button", { name: "Restore" }).click()
  await expect(page.getByRole("button", { name: "Edit details" })).toBeVisible()
  await page.getByRole("button", { name: `More actions for ${feedName} Edited` }).click()
  await page.getByRole("alertdialog").getByRole("button", { name: "Archive feed" }).click()
  await expect(page.getByRole("alertdialog")).toBeHidden()
  await page.getByRole("button", { name: `${feedName} Edited`, exact: true }).click()
  await page.getByRole("button", { name: "Delete permanently" }).click()
  await expect(page.getByRole("alertdialog")).toContainText("This cannot be undone.")
  await page.getByRole("alertdialog").getByRole("button", { name: "Cancel" }).click()
  await expect(page.getByRole("heading", { name: `${feedName} Edited` })).toBeVisible()
  await page.getByRole("button", { name: "Delete permanently" }).click()
  await page.getByRole("alertdialog").getByRole("button", { name: "Delete permanently" }).click()
  await expect(page.getByText("No active feeds yet.")).toBeVisible()

  await page.getByRole("button", { name: "Sign out" }).click()
  await expect(page.getByRole("heading", { name: "Welcome back" })).toBeVisible()
})
